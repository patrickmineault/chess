#!/usr/bin/env python3
"""
Validate chess notation scenarios generated by bench_chess_notation.py.

Walks through all results in results_cn/, validates each scenario,
generates board images, and creates a results.csv summary.

Usage:
    python validate_chess_notation.py
    python validate_chess_notation.py --input ./results_cn
    python validate_chess_notation.py --no-images  # Skip image generation
"""

import argparse
import csv
import json
from pathlib import Path

import chess
import chess.svg
import cairosvg


def render_board(board: chess.Board, filename: str, last_move: chess.Move = None) -> None:
    """Render the board to a PNG file."""
    svg_string = chess.svg.board(board, lastmove=last_move)
    cairosvg.svg2png(bytestring=svg_string.encode(), write_to=filename)


def transform_board(board: chess.Board, transform_func) -> chess.Board:
    """Apply a square transformation to create a new board."""
    new_board = chess.Board(None)  # Empty board
    new_board.turn = board.turn

    for square in chess.SQUARES:
        piece = board.piece_at(square)
        if piece:
            new_square = transform_func(square)
            new_board.set_piece_at(new_square, piece)

    return new_board


def vertical_flip(square: int) -> int:
    """Flip vertically (rank mirror)."""
    return chess.square_mirror(square)


def horizontal_flip(square: int) -> int:
    """Flip horizontally (file mirror)."""
    file = chess.square_file(square)
    rank = chess.square_rank(square)
    return chess.square(7 - file, rank)


def rotate_180(square: int) -> int:
    """Rotate 180 degrees."""
    file = chess.square_file(square)
    rank = chess.square_rank(square)
    return chess.square(7 - file, 7 - rank)


def get_canonical_board_fen(board: chess.Board) -> str:
    """
    Get canonical representation of a board position.

    Generates all transformations (identity, vertical flip, horizontal flip,
    180 degree rotation) and returns the lexicographically smallest board FEN.
    This allows detecting positions that are equivalent via rotation/reflection.
    """
    transforms = [
        lambda s: s,  # identity
        vertical_flip,
        horizontal_flip,
        rotate_180,
    ]

    fens = []
    for transform in transforms:
        transformed = transform_board(board, transform)
        # Only compare position part of FEN (first field)
        position_fen = transformed.board_fen()
        fens.append(position_fen)

    return min(fens)


def validate_fen(fen: str) -> tuple[chess.Board | None, str]:
    """
    Validate FEN notation and return board if valid.

    Returns (board, error_message). Board is None if invalid.
    """
    try:
        board = chess.Board(fen)
    except ValueError as e:
        return None, f"Invalid FEN: {e}"

    if not board.is_valid():
        return None, "Invalid position (illegal board state)"

    return board, ""


def validate_white_to_move(board: chess.Board) -> tuple[bool, str]:
    """Check if it's white's turn to move."""
    if board.turn != chess.WHITE:
        return False, "Not white's turn to move"
    return True, ""


def parse_move(move_str: str) -> str:
    """
    Clean up move notation.

    Handles formats like:
    - "Qb8#"
    - "1.Qb8#"
    - "1. Qb8#"
    - "Qb8"
    """
    move_san = move_str.strip()

    # Remove move number prefix if present (e.g., "1.Qb8#" -> "Qb8#")
    if "." in move_san:
        move_san = move_san.split(".")[-1].strip()

    # Remove check/checkmate symbols for parsing (we'll verify checkmate separately)
    # Keep the original for display
    return move_san


def validate_checkmate_in_one(board: chess.Board, move_str: str) -> tuple[bool, str, chess.Move | None]:
    """
    Validate that the given move results in checkmate.

    Returns (is_valid, error_message, move_object)
    """
    move_san = parse_move(move_str)

    # Try to parse the move
    try:
        move = board.parse_san(move_san)
    except chess.InvalidMoveError:
        return False, f"Invalid move notation: {move_san}", None
    except chess.IllegalMoveError:
        return False, f"Illegal move: {move_san}", None
    except chess.AmbiguousMoveError:
        return False, f"Ambiguous move notation: {move_san}", None
    except Exception as e:
        return False, f"Error parsing move: {e}", None

    # Check if move is legal
    if move not in board.legal_moves:
        return False, f"Move {move_san} is not legal in this position", None

    # Make the move and check for checkmate
    board_copy = board.copy()
    board_copy.push(move)

    if not board_copy.is_checkmate():
        if board_copy.is_check():
            return False, f"Move gives check but not checkmate", move
        else:
            return False, f"Move does not give check", move

    return True, "", move


def validate_scenario(scenario: dict) -> dict:
    """
    Validate a single scenario.

    Returns dict with validation results.
    """
    result = {
        "name": scenario.get("name", ""),
        "fen": scenario.get("fen", ""),
        "move": scenario.get("move", ""),
        "fen_valid": False,
        "white_to_move": False,
        "move_valid": False,
        "is_checkmate": False,
        "error": "",
        "board": None,
        "move_object": None,
        "canonical_fen": "",
    }

    # Validate FEN
    board, error = validate_fen(scenario.get("fen", ""))
    if board is None:
        result["error"] = error
        return result
    result["fen_valid"] = True
    result["board"] = board
    result["canonical_fen"] = get_canonical_board_fen(board)

    # Validate white to move
    is_white, error = validate_white_to_move(board)
    if not is_white:
        result["error"] = error
        return result
    result["white_to_move"] = True

    # Validate checkmate in one
    move_str = scenario.get("move", "")
    if not move_str:
        result["error"] = "No move provided"
        return result

    is_mate, error, move_obj = validate_checkmate_in_one(board, move_str)
    result["move_object"] = move_obj

    if move_obj is not None:
        result["move_valid"] = True

    if is_mate:
        result["is_checkmate"] = True
    else:
        result["error"] = error

    return result


def process_run_folder(run_dir: Path, generate_images: bool = True) -> list[dict]:
    """
    Process a single run folder and validate all scenarios.

    Returns list of validation results.
    """
    scenarios_file = run_dir / "scenarios.json"
    if not scenarios_file.exists():
        return []

    try:
        scenarios = json.loads(scenarios_file.read_text())
    except json.JSONDecodeError:
        return []

    # Read completion tokens from metadata.json (proxy for reasoning length)
    metadata_file = run_dir / "metadata.json"
    reasoning_length = 0
    if metadata_file.exists():
        try:
            metadata = json.loads(metadata_file.read_text())
            reasoning_length = metadata.get("usage", {}).get("completion_tokens", 0)
        except Exception:
            pass

    results = []

    for i, scenario in enumerate(scenarios):
        validation = validate_scenario(scenario)
        validation["scenario_index"] = i
        validation["run_dir"] = str(run_dir)
        validation["reasoning_length"] = reasoning_length

        # Generate board images if requested and FEN is valid
        if generate_images and validation["board"] is not None:
            board = validation["board"]

            # Render before position
            before_path = run_dir / f"board_{i}_before.png"
            try:
                render_board(board, str(before_path))
                validation["image_before"] = str(before_path)
            except Exception as e:
                validation["image_before"] = f"Error: {e}"

            # Render after position if move is valid
            if validation["move_object"] is not None:
                board_after = board.copy()
                board_after.push(validation["move_object"])
                after_path = run_dir / f"board_{i}_after.png"
                try:
                    render_board(board_after, str(after_path), last_move=validation["move_object"])
                    validation["image_after"] = str(after_path)
                except Exception as e:
                    validation["image_after"] = f"Error: {e}"

        # Remove non-serializable objects before adding to results
        validation.pop("board", None)
        validation.pop("move_object", None)

        results.append(validation)

    # Save validation results to the run folder
    validation_file = run_dir / "validation.json"
    validation_file.write_text(json.dumps(results, indent=2))

    return results


def find_all_runs(input_dir: Path) -> list[Path]:
    """Find all run directories in the results folder."""
    runs = []

    # Pattern: results_cn/{model}/effort_{level}/num_{n}/run_{i}
    for run_dir in input_dir.rglob("run_*"):
        if run_dir.is_dir() and (run_dir / "scenarios.json").exists():
            runs.append(run_dir)

    return sorted(runs)


def parse_run_path(run_dir: Path, base_dir: Path) -> dict:
    """Extract model, effort, num, run from path."""
    try:
        rel_path = run_dir.relative_to(base_dir)
        parts = rel_path.parts

        # Expected: {provider}/{model}/effort_{level}/num_{n}/run_{i}
        # e.g., anthropic/claude-sonnet-4.5/effort_high/num_3/run_1
        # Model name includes provider: "anthropic/claude-sonnet-4.5"
        if len(parts) >= 5:
            model = f"{parts[0]}/{parts[1]}"
            effort = parts[2].replace("effort_", "")
            num = parts[3].replace("num_", "")
            run = parts[4].replace("run_", "")
        else:
            # Fallback for unexpected structure
            model = "/".join(parts[:-3]) if len(parts) > 3 else ""
            effort = parts[-3].replace("effort_", "") if len(parts) > 2 else ""
            num = parts[-2].replace("num_", "") if len(parts) > 1 else ""
            run = parts[-1].replace("run_", "") if len(parts) > 0 else ""

        return {
            "model": model,
            "effort": effort,
            "num_requested": num,
            "run": run,
        }
    except Exception:
        return {
            "model": "",
            "effort": "",
            "num_requested": "",
            "run": "",
        }


def main():
    parser = argparse.ArgumentParser(
        description="Validate chess notation scenarios and generate results",
    )
    parser.add_argument(
        "--input",
        type=str,
        default="./results_cn",
        help="Input directory containing results (default: ./results_cn)",
    )
    parser.add_argument(
        "--no-images",
        action="store_true",
        help="Skip generating board images",
    )

    args = parser.parse_args()
    input_dir = Path(args.input)

    if not input_dir.exists():
        print(f"Error: Input directory '{input_dir}' does not exist")
        return 1

    # Find all run directories
    run_dirs = find_all_runs(input_dir)
    print(f"Found {len(run_dirs)} run directories to process")

    if not run_dirs:
        print("No runs found. Make sure scenarios.json files exist.")
        return 1

    # Process all runs
    all_results = []
    generate_images = not args.no_images

    for i, run_dir in enumerate(run_dirs):
        print(f"[{i+1}/{len(run_dirs)}] Processing {run_dir.relative_to(input_dir)}...")

        path_info = parse_run_path(run_dir, input_dir)
        results = process_run_folder(run_dir, generate_images=generate_images)

        for r in results:
            r.update(path_info)
            all_results.append(r)

        # Print summary for this run
        valid_count = sum(1 for r in results if r["is_checkmate"])
        print(f"    {valid_count}/{len(results)} valid checkmates")

    # Generate CSV summary
    csv_path = input_dir / "results.csv"

    fieldnames = [
        "model",
        "effort",
        "num_requested",
        "run",
        "scenario_index",
        "name",
        "fen",
        "canonical_fen",
        "move",
        "fen_valid",
        "white_to_move",
        "move_valid",
        "is_checkmate",
        "reasoning_length",
        "error",
    ]

    with open(csv_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(all_results)

    print(f"\nResults saved to {csv_path}")

    # Print overall summary
    total = len(all_results)
    valid_fen = sum(1 for r in all_results if r["fen_valid"])
    valid_move = sum(1 for r in all_results if r["move_valid"])
    valid_mate = sum(1 for r in all_results if r["is_checkmate"])
    # Count unique valid checkmates (by canonical FEN)
    unique_valid_fens = set(
        r["canonical_fen"] for r in all_results
        if r["is_checkmate"] and r["canonical_fen"]
    )
    unique_valid_mate = len(unique_valid_fens)

    print("\n" + "=" * 60)
    print("VALIDATION SUMMARY")
    print("=" * 60)
    print(f"Total scenarios:     {total}")
    print(f"Valid FEN:           {valid_fen} ({100*valid_fen/total:.1f}%)" if total > 0 else "Valid FEN:           0")
    print(f"Valid move:          {valid_move} ({100*valid_move/total:.1f}%)" if total > 0 else "Valid move:          0")
    print(f"Valid checkmate:     {valid_mate} ({100*valid_mate/total:.1f}%)" if total > 0 else "Valid checkmate:     0")
    print(f"Unique valid mates:  {unique_valid_mate} ({100*unique_valid_mate/total:.1f}%)" if total > 0 else "Unique valid mates:  0")
    print("=" * 60)

    # Print granular summary
    # Key insight: denominator should be num_requested per run, not scenarios parsed
    if all_results:
        from collections import defaultdict

        # First, group results by run to calculate per-run stats
        # Each run has a num_requested that determines expected scenarios
        # Track canonical FENs to count unique valid positions
        # Track reasoning length per run (same for all scenarios in a run)
        run_data = defaultdict(lambda: {"num_requested": 0, "valid": 0, "canonical_fens": set(), "reasoning_length": 0})

        for r in all_results:
            # Unique run key
            run_key = (r["model"], r["effort"], r["num_requested"], r["run"])
            num_req = int(r["num_requested"]) if r["num_requested"].isdigit() else 0
            run_data[run_key]["num_requested"] = num_req
            run_data[run_key]["reasoning_length"] = r.get("reasoning_length", 0)
            if r["is_checkmate"]:
                run_data[run_key]["valid"] += 1
                if r["canonical_fen"]:
                    run_data[run_key]["canonical_fens"].add(r["canonical_fen"])

        # Calculate unique valid per run
        for run_key in run_data:
            run_data[run_key]["unique_valid"] = len(run_data[run_key]["canonical_fens"])

        # Now aggregate by model/effort/num using num_requested as denominator
        granular_stats = defaultdict(lambda: {"expected": 0, "valid": 0, "unique_valid": 0, "runs": 0, "canonical_fens": set(), "reasoning_lengths": []})

        for (model, effort, num, run), data in run_data.items():
            key = (model, effort, num)
            granular_stats[key]["expected"] += data["num_requested"]
            granular_stats[key]["valid"] += data["valid"]
            granular_stats[key]["unique_valid"] += data["unique_valid"]
            granular_stats[key]["runs"] += 1
            granular_stats[key]["canonical_fens"].update(data["canonical_fens"])
            granular_stats[key]["reasoning_lengths"].append(data["reasoning_length"])

        # Print detailed breakdown
        print("\nDETAILED BREAKDOWN (Model / Effort / Num)")
        print("-" * 130)
        print(f"{'Model':<40} {'Effort':<8} {'Num':<5} {'Runs':<6} {'Valid':<14} {'Unique':<14} {'Avg Reasoning':<12}")
        print("-" * 130)

        for (model, effort, num) in sorted(granular_stats.keys()):
            stats = granular_stats[(model, effort, num)]
            pct = 100 * stats["valid"] / stats["expected"] if stats["expected"] > 0 else 0
            unique_pct = 100 * stats["unique_valid"] / stats["expected"] if stats["expected"] > 0 else 0
            avg_reasoning = sum(stats["reasoning_lengths"]) / len(stats["reasoning_lengths"]) if stats["reasoning_lengths"] else 0
            print(f"{model:<40} {effort:<8} {num:<5} {stats['runs']:<6} {stats['valid']:>3}/{stats['expected']:<3} ({pct:>5.1f}%) {stats['unique_valid']:>3}/{stats['expected']:<3} ({unique_pct:>5.1f}%) {avg_reasoning:>10.0f} tokens")

        # Aggregate by model only
        print("\n" + "-" * 130)
        print("AGGREGATE BY MODEL")
        print("-" * 130)

        model_stats = defaultdict(lambda: {"expected": 0, "valid": 0, "unique_valid": 0, "canonical_fens": set(), "reasoning_lengths": []})
        for (model, effort, num), stats in granular_stats.items():
            model_stats[model]["expected"] += stats["expected"]
            model_stats[model]["valid"] += stats["valid"]
            model_stats[model]["unique_valid"] += stats["unique_valid"]
            model_stats[model]["canonical_fens"].update(stats["canonical_fens"])
            model_stats[model]["reasoning_lengths"].extend(stats["reasoning_lengths"])

        for model in sorted(model_stats.keys()):
            stats = model_stats[model]
            pct = 100 * stats["valid"] / stats["expected"] if stats["expected"] > 0 else 0
            unique_pct = 100 * stats["unique_valid"] / stats["expected"] if stats["expected"] > 0 else 0
            avg_reasoning = sum(stats["reasoning_lengths"]) / len(stats["reasoning_lengths"]) if stats["reasoning_lengths"] else 0
            print(f"{model:<40} {stats['valid']:>3}/{stats['expected']:<3} ({pct:>5.1f}%) unique: {stats['unique_valid']:>3}/{stats['expected']:<3} ({unique_pct:>5.1f}%) avg reasoning: {avg_reasoning:>8.0f} tokens")

        # Aggregate by effort level
        print("\n" + "-" * 130)
        print("AGGREGATE BY EFFORT")
        print("-" * 130)

        effort_stats = defaultdict(lambda: {"expected": 0, "valid": 0, "unique_valid": 0, "reasoning_lengths": []})
        for (model, effort, num), stats in granular_stats.items():
            effort_stats[effort]["expected"] += stats["expected"]
            effort_stats[effort]["valid"] += stats["valid"]
            effort_stats[effort]["unique_valid"] += stats["unique_valid"]
            effort_stats[effort]["reasoning_lengths"].extend(stats["reasoning_lengths"])

        for effort in sorted(effort_stats.keys()):
            stats = effort_stats[effort]
            pct = 100 * stats["valid"] / stats["expected"] if stats["expected"] > 0 else 0
            unique_pct = 100 * stats["unique_valid"] / stats["expected"] if stats["expected"] > 0 else 0
            avg_reasoning = sum(stats["reasoning_lengths"]) / len(stats["reasoning_lengths"]) if stats["reasoning_lengths"] else 0
            print(f"{effort:<40} {stats['valid']:>3}/{stats['expected']:<3} ({pct:>5.1f}%) unique: {stats['unique_valid']:>3}/{stats['expected']:<3} ({unique_pct:>5.1f}%) avg reasoning: {avg_reasoning:>8.0f} tokens")

        # Aggregate by num_requested
        print("\n" + "-" * 130)
        print("AGGREGATE BY NUM REQUESTED")
        print("-" * 130)

        num_stats = defaultdict(lambda: {"expected": 0, "valid": 0, "unique_valid": 0, "reasoning_lengths": []})
        for (model, effort, num), stats in granular_stats.items():
            num_stats[num]["expected"] += stats["expected"]
            num_stats[num]["valid"] += stats["valid"]
            num_stats[num]["unique_valid"] += stats["unique_valid"]
            num_stats[num]["reasoning_lengths"].extend(stats["reasoning_lengths"])

        for num in sorted(num_stats.keys(), key=lambda x: int(x) if x.isdigit() else 0):
            stats = num_stats[num]
            pct = 100 * stats["valid"] / stats["expected"] if stats["expected"] > 0 else 0
            unique_pct = 100 * stats["unique_valid"] / stats["expected"] if stats["expected"] > 0 else 0
            avg_reasoning = sum(stats["reasoning_lengths"]) / len(stats["reasoning_lengths"]) if stats["reasoning_lengths"] else 0
            print(f"num={num:<37} {stats['valid']:>3}/{stats['expected']:<3} ({pct:>5.1f}%) unique: {stats['unique_valid']:>3}/{stats['expected']:<3} ({unique_pct:>5.1f}%) avg reasoning: {avg_reasoning:>8.0f} tokens")

    return 0


if __name__ == "__main__":
    exit(main())
